let current = { bank: 0, item: 0, selected: null, checked: false };
let sound = true,
  ctx;
const menu = document.getElementById("menu"),
  home = document.getElementById("home"),
  stage = document.getElementById("stage");
function renderMenu() {
  menu.innerHTML = "";
  banks.forEach((b, i) => {
    let btn = document.createElement("button");
    btn.className = "tile";
    btn.innerHTML = `<span class="num">${i + 1}</span><b>${b.icon} ${b.title}</b><small>${b.desc} · ${b.items.length} հարց</small>`;
    btn.onclick = () => openBank(i);
    menu.appendChild(btn);
  });
}
function tone(ok = true) {
  if (!sound) return;
  try {
    ctx = ctx || new (window.AudioContext || window.webkitAudioContext)();
    let o = ctx.createOscillator(),
      g = ctx.createGain();
    o.connect(g);
    g.connect(ctx.destination);
    o.type = "sine";
    o.frequency.value = ok ? 660 : 220;
    g.gain.setValueAtTime(0.0001, ctx.currentTime);
    g.gain.exponentialRampToValueAtTime(0.12, ctx.currentTime + 0.02);
    g.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 0.28);
    o.start();
    o.stop(ctx.currentTime + 0.3);
  } catch (e) {}
}
function showHome() {
  stage.classList.add("hidden");
  home.classList.remove("hidden");
  window.scrollTo({ top: 0, behavior: "smooth" });
}
function openBank(i) {
  current = { bank: i, item: 0, selected: null, checked: false };
  home.classList.add("hidden");
  stage.classList.remove("hidden");
  renderQuestion();
  window.scrollTo({ top: 0, behavior: "smooth" });
}
function renderQuestion() {
  let b = banks[current.bank],
    q = b.items[current.item],
    pct = ((current.item + 1) / b.items.length) * 100;
  stage.innerHTML = `<div class="backrow"><button class="secondary" onclick="showHome()">← Բաժինների ցանկ</button><span class="tag">${b.icon} ${b.title}</span><span class="note">Հարց ${current.item + 1} / ${b.items.length}</span></div>
<div class="progress"><span style="width:${pct}%"></span></div><div class="panel"><div class="eyebrow">Մտածի՛ր և ընտրի՛ր</div><div class="question">${q.q}</div><div class="options">${q.opts.map((o, i) => `<button class="option ${current.selected === i ? "selected" : ""}" onclick="selectOption(${i})">${["Ա", "Բ", "Գ", "Դ"][i]}. ${o}</button>`).join("")}</div>
<div class="actions"><button class="primary" onclick="checkAnswer()" ${current.selected === null || current.checked ? "disabled" : ""}>✓ Ստուգել պատասխանը</button><button class="secondary" onclick="nextQuestion()">${current.item === b.items.length - 1 ? "Ավարտել բաժինը" : "Հաջորդ հարց →"}</button></div>
<div id="feedback" class="feedback ${current.checked ? "show" : ""} ${current.checked && current.selected !== q.a ? "bad" : ""}">${current.checked ? `<b>${current.selected === q.a ? "Ճի՛շտ է։ 🌟" : "Փորձի՛ր հիշել ճիշտ տարբերակը։"}</b><br>${q.why}` : ""}</div></div>`;
}
function selectOption(i) {
  if (current.checked) return;
  current.selected = i;
  renderQuestion();
}
function checkAnswer() {
  if (current.selected === null || current.checked) return;
  current.checked = true;
  let good = current.selected === banks[current.bank].items[current.item].a;
  tone(good);
  renderQuestion();
  let f = document.getElementById("feedback");
  f.scrollIntoView({ behavior: "smooth", block: "nearest" });
}
function nextQuestion() {
  let b = banks[current.bank];
  if (current.item < b.items.length - 1) {
    current.item++;
    current.selected = null;
    current.checked = false;
    renderQuestion();
  } else {
    stage.innerHTML = `<div class="panel"><div class="eyebrow">Բաժինն ավարտված է</div><h2>Հիանալի աշխատանք։ 🎉</h2><p class="lead">Դու ավարտեցիր «${b.title}» բաժնի հարցերը։ Վերադարձի՛ր ցանկին և ընտրի՛ր հաջորդ թեման։</p><div class="actions"><button class="primary" onclick="showHome()">Վերադառնալ բաժիններին</button></div></div>`;
    tone(true);
  }
}
document.getElementById("soundBtn").onclick = () => {
  sound = !sound;
  document.getElementById("soundBtn").textContent = sound
    ? "🔊 Ձայն՝ միացված"
    : "🔇 Ձայն՝ անջատված";
  if (sound) tone(true);
};
